<h2>Почему «Кубатура»</h2>
<p>
	 Формат центра экономит время и помогает сделать ремонт в едином стиле — не нужно объезжать десятки магазинов по всему городу:
</p>
<ul class="check">
	<li><strong>Всё под одной крышей</strong> — от черновых материалов до финального декора в одном здании.</li>
	<li><strong>Десятки магазинов и брендов</strong> — широкий выбор в каждом разделе и разные ценовые сегменты.</li>
	<li><strong>Сравнение вживую</strong> — образцы плитки, дверей, напольных покрытий и сантехники можно посмотреть рядом.</li>
	<li><strong>Консультации и услуги</strong> — замер, доставка и помощь специалистов магазинов-резидентов.</li>
</ul>
